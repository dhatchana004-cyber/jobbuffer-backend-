/**
 * Returns a real company logo. Never returns the generic unsplash stock photo.
 */
export function getCompanyLogo(companyName?: string, rawLogo?: string | null): string {
  if (rawLogo && typeof rawLogo === 'string' && rawLogo.trim()) {
    // If it's the generic unsplash stock photo of people at a desk, ignore it
    if (!rawLogo.includes('1549923746')) {
      return rawLogo.trim();
    }
  }

  const norm = (companyName || '').toLowerCase().trim();
  if (!norm) {
    return 'https://ui-avatars.com/api/?name=Company&background=2563eb&color=ffffff&size=128&bold=true';
  }

  // Exact or partial match in official map
  for (const [key, logoUrl] of Object.entries(COMPANY_LOGO_MAP)) {
    if (norm === key || norm.includes(key) || key.includes(norm)) {
      return logoUrl;
    }
  }

  // Fallback to high-res branded monogram avatar
  return `https://ui-avatars.com/api/?name=${encodeURIComponent(companyName || 'Company')}&background=1e40af&color=ffffff&size=128&bold=true`;
}

